"""Write the comparison tables of the email, RTF or ODF benchmark.

    python -I report_doc.py FORMAT DATA_DIR [GOGC_DIR] > comparison.md

FORMAT is email, rtf or odf. DATA_DIR holds, for each set of files
(email: email; rtf: rtf; odf: odt, ods, odp), results-SET/TOOL-WORKERS
(run_all_doc.sh) and scores-SET.json (score_email.py for email,
score_text.py against LibreOffice for the others; for ODS also
scores-ods-shown.json, against cells as displayed), and SET.list.
GOGC_DIR, if given, holds SET/gogcG-W/measure.json: go-fast run with
GOGC=G (100, 200, 400) and W workers.
"""
import json, os, platform, subprocess, sys
from importlib import metadata

FORMAT, D = sys.argv[1], sys.argv[2]
GOGC_DIR = sys.argv[3] if len(sys.argv) > 3 else None
LIB = {"email": "go-fast-email", "rtf": "go-fast-rtf", "odf": "go-fast-odf"}[FORMAT]
SETS = {"email": ["email"], "rtf": ["rtf"], "odf": ["odt", "ods", "odp"]}[FORMAT]
LABEL = {"go-fast": f"**{LIB}**", "stdlib-email": "Python `email` (stdlib)", "mail-parser": "mail-parser (Python)",
         "eml-parser": "eml-parser (Python)", "kreuzberg": "Kreuzberg (Rust core, Python)", "rs-mail-parser": "mail-parser (Rust crate)",
         "striprtf": "striprtf (Python)", "pandoc": "pandoc (a process a file)", "rs-rtf-parser": "rtf-parser (Rust crate)",
         "odfpy": "odfpy (Python)", "pandas-odf": "pandas `read_excel` (odf engine)", "rs-calamine": "calamine (Rust crate)"}
WHAT = {"email": "7,551 messages, 56 MB: two months (2025-09 and -10) of eight Apache mailing lists (as their archives export "
                 "them, with the mbox `From ` line) and the SpamAssassin public corpus (ham and spam, 2002-2005: HTML, "
                 "attachments, old character sets)",
        "rtf": "{n:,} RTF files, {mb:.0f} MB, from Common Crawl (CC-MAIN-2025-43), as served",
        "odt": "{n:,} ODT files, {mb:.0f} MB, from Common Crawl (CC-MAIN-2025-43), as served",
        "ods": "{n:,} ODS files, {mb:.0f} MB, from Common Crawl (CC-MAIN-2025-43), as served",
        "odp": "{n:,} ODP files, {mb:.0f} MB, from Common Crawl (CC-MAIN-2025-43), as served"}
NOTES = {"rtf": "go-fast-rtf's 4 failures are files that are not RTF (one plain UTF-8 text, three PHP warning pages, "
                "served as RTF); it refuses them as not RTF, where the other tools give their bytes as text.",
         "odt": "", "ods": "", "odp": "Kreuzberg does not read ODP; no tool used here besides odfpy does.", "email": ""}


def runs(set_, workers):
    rows = []
    R = os.path.join(D, "results-" + set_)
    for t in LABEL:
        d = os.path.join(R, f"{t}-{workers}")
        if not os.path.exists(os.path.join(d, "measure.json")):
            continue
        m = json.load(open(os.path.join(d, "measure.json")))
        res = [json.loads(l) for l in open(os.path.join(d, "results.jsonl"))]
        ts = sorted(x["s"] for x in res if not x["err"]) or [0]
        q = lambda p: ts[int(p * (len(ts) - 1))] * 1000
        busy = m.get("others_cpu_s", 0) > max(0.05 * m["cpu_s"], 2)
        rows.append({"tool": t, "wall_s": m["wall_s"], "cpu_s": m["cpu_s"], "peak_mb": m["peak_rss_mb"], "files": len(res),
                     "others_cpu_s": m.get("others_cpu_s", 0), "disturbed": busy,
                     "failed": sum(1 for x in res if x["err"]), "p50_ms": q(.5), "p95_ms": q(.95), "p99_ms": q(.99),
                     "max_ms": ts[-1] * 1000})
    return sorted(rows, key=lambda r: r["wall_s"])


def versions():
    v = {}
    for p in ["mail-parser", "eml-parser", "kreuzberg", "striprtf", "odfpy", "pandas"]:
        try:
            v[p] = metadata.version(p)
        except metadata.PackageNotFoundError:
            pass
    pv = subprocess.run(["pandoc", "--version"], capture_output=True, text=True).stdout.split("\n")[0]
    if pv:
        v["pandoc"] = pv.split()[-1]
    lock = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rsdoc", "Cargo.lock")
    if os.path.exists(lock):
        name = None
        for l in open(lock):
            if l.startswith("name = "):
                name = l.split('"')[1]
            elif l.startswith("version = ") and name in ("mail-parser", "rtf-parser", "calamine"):
                v[name + " (crate)"] = l.split('"')[1]
    return v


cpu = next((l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name")), platform.processor())
gov = subprocess.run(["go", "version"], capture_output=True, text=True).stdout.strip()
print(f"# {LIB} against the tools in use today\n")
print("Generated by `bench/report_doc.py`; do not edit. Numbers are from one machine and compare tools on that machine only.\n")
print(f"Machine: {cpu}, {os.cpu_count()} logical cores, {platform.platform()}, Python {platform.python_version()}, {gov}. "
      "Each run waited for the machine to be quiet and was repeated if other processes used it meanwhile (`measure.py`).\n")
print("Versions: " + ", ".join(f"{k} {v}" for k, v in versions().items()) + ".\n")
print("Each tool reads every file in one long-lived process, the way a pipeline does, with one worker and with 24; "
      "the time of a file is the call alone, after its bytes are read. Wall time, CPU time and peak memory are of the whole "
      "process tree.\n")
out = {}
for s in SETS:
    files = [l.strip() for l in open(os.path.join(D, s + ".list")) if l.strip()]
    mb = sum(os.path.getsize(f) for f in files) / 2**20
    print(f"## {s.upper() if s != 'email' else 'Email'}\n")
    print("**Input:** " + WHAT[s].format(n=len(files), mb=mb) + ".\n")
    one, many = runs(s, 1), runs(s, 24)
    out[s] = {"files": len(files), "one_worker": one, "24_workers": many}
    for title, rows in (("One worker", one), ("24 workers", many)):
        if not rows:
            continue
        print(f"### {title}\n")
        print(f"| Tool | Wall | Against {LIB} | CPU | Peak memory | Failed | Median | 95th | 99th | Slowest file |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        base = next(r["wall_s"] for r in rows if r["tool"] == "go-fast")
        for r in rows:
            rel = "" if r["tool"] == "go-fast" else f"{r['wall_s'] / base:.2f} times"
            mark = " ¹" if r["disturbed"] else ""
            print(f"| {LABEL[r['tool']]}{mark} | {r['wall_s']:.2f} s | {rel} | {r['cpu_s']:.1f} s | {r['peak_mb']:,.0f} MB | "
                  f"{r['failed']} | {r['p50_ms']:.2f} ms | {r['p95_ms']:.2f} ms | {r['p99_ms']:.2f} ms | {r['max_ms']:.0f} ms |")
        print()
        for r in rows:
            if r["disturbed"]:
                print(f"¹ Other processes used {r['others_cpu_s']:.0f} s of CPU during this run, after five attempts to "
                      "find the machine quiet; its time may be a little high.\n")
    if NOTES[s]:
        print(NOTES[s] + "\n")
    if GOGC_DIR and os.path.exists(os.path.join(GOGC_DIR, s, "gogc100-1", "measure.json")):
        g = {}
        for gc in (100, 200, 400):
            for w in (1, 24):
                m = json.load(open(os.path.join(GOGC_DIR, s, f"gogc{gc}-{w}", "measure.json")))
                g[f"{gc}-{w}"] = {"wall_s": m["wall_s"], "peak_mb": m["peak_rss_mb"]}
        out[s]["gogc"] = g
        print(f"### {LIB} and `GOGC`\n")
        print("Go's garbage collector can be given more memory for less work with `GOGC` in the environment "
              "(or `debug.SetGCPercent`); the library and its command keep Go's default, 100. The same run as above "
              "with each setting (wall time, peak memory):\n")
        print("| `GOGC` | One worker | Peak | 24 workers | Peak |")
        print("|---|---|---|---|---|")
        for gc in (100, 200, 400):
            a, b = g[f"{gc}-1"], g[f"{gc}-24"]
            label = "100 (default)" if gc == 100 else str(gc)
            print(f"| {label} | {a['wall_s']:.2f} s | {a['peak_mb']:,.0f} MB | {b['wall_s']:.2f} s | {b['peak_mb']:,.0f} MB |")
        print()
    sp = os.path.join(D, f"scores-{s}.json")
    if not os.path.exists(sp):
        continue
    sc = json.load(open(sp))
    out[s]["scores"] = sc
    print("### Accuracy\n")
    if s == "ods":
        print("A cell holds its value (42956178) and, beside it, its text as displayed (42,956,178). "
              "go-fast-odf and odfpy give the text displayed; calamine, pandas and Kreuzberg give the value. Words are runs "
              "of letters and digits, so the two disagree on every formatted number, date and percentage, and each "
              "scores well against one export and less well against the other. Both are shown.\n")
    if s == "email":
        n = next(iter(sc.values()))["plain_bodies"]
        print(f"On the {n:,} messages whose body (the part Python's `email` package prefers) is plain text that it decodes "
              "without error: the share of that body's words a tool's text holds (`score_email.py`; the tools add headers, "
              "so precision says little).\n")
        print("| Tool | Body recall |")
        print("|---|---|")
        for k, v in sorted(sc.items(), key=lambda kv: -(kv[1]["body_recall"] or 0)):
            print(f"| {LABEL.get(k, k)} | {v['body_recall']:.4f} |")
    else:
        print(f"Against LibreOffice's own export ({'CSV of every sheet' if s == 'ods' else 'text'}) of {sc['pages']} files "
              "chosen at random (`reference_doc.py`; files with fewer than 20 words left out), by words (`score_text.py`: "
              "precision is the share of a tool's words in the reference, recall the share of the reference's words the "
              "tool gives, averaged over files; a file a tool failed on scores 0).\n")
        shown = os.path.join(D, "scores-ods-shown.json")
        if s == "ods" and os.path.exists(shown):
            sh = json.load(open(shown))
            out[s]["scores_shown"] = sh
            print(f"| Tool | F1, values | Precision | Recall | F1, as displayed ({sh['pages']} files) | Precision | Recall |")
            print("|---|---|---|---|---|---|---|")
            for k, v in sorted(sc["tools"].items(), key=lambda kv: -kv[1]["f1"]):
                name, w = k.rsplit("-", 1)[0], sh["tools"][k]
                print(f"| {LABEL.get(name, name)} | {v['f1']:.3f} | {v['precision']:.3f} | {v['recall']:.3f} | "
                      f"{w['f1']:.3f} | {w['precision']:.3f} | {w['recall']:.3f} |")
        else:
            print("| Tool | F1 | Precision | Recall |")
            print("|---|---|---|---|")
            for k, v in sorted(sc["tools"].items(), key=lambda kv: -kv[1]["f1"]):
                name = k.rsplit("-", 1)[0]
                print(f"| {LABEL.get(name, name)} | {v['f1']:.3f} | {v['precision']:.3f} | {v['recall']:.3f} |")
    print()
json.dump({"versions": versions(), "sets": out}, open(os.path.join(D, f"comparison-{FORMAT}.json"), "w"), indent=1)
